import type { Analysis, Claim } from "./schema";
import { bandLabel } from "./score";

/**
 * Markdown is the primary export: it survives pasting into Notion, Slack, a
 * README, or a pull request. PDF is the version you send to someone who does
 * not open links.
 */

export function toMarkdown(analysis: Analysis): string {
  const lines: string[] = [];
  const date = new Date(analysis.createdAt).toLocaleDateString("en-GB", {
    year: "numeric",
    month: "long",
    day: "numeric",
  });

  lines.push(`# Load-Bearing report: ${analysis.title}`);
  lines.push("");
  lines.push(`_${date} · ${analysis.claims.length} claims · top assumption ranked first_`);
  lines.push("");
  lines.push("## What the plan is trying to do");
  lines.push("");
  lines.push(analysis.summary);
  lines.push("");
  lines.push("## The claims it rests on");
  lines.push("");

  for (const claim of analysis.claims) {
    lines.push(`### ${claim.rank}. ${claim.claim}`);
    lines.push("");
    lines.push(
      `- **${bandLabel(claim.priority)}** · impact ${claim.impact}/5 · confidence ${claim.confidence}`
    );
    lines.push(`- Category: ${claim.category}`);
    lines.push(`- Status: ${claim.status}`);
    lines.push(
      `- Source: ${
        claim.source === "implied" ? "_implied — never stated in the plan_" : `“${claim.source}”`
      }`
    );
    if (claim.dependsOn.length) {
      lines.push(`- Only matters if: ${claim.dependsOn.join(", ")}`);
    }
    lines.push("");
    lines.push(claim.reasoning);
    if (claim.evidence.length) {
      lines.push("");
      lines.push("**Evidence**");
      for (const e of claim.evidence) {
        lines.push(`- [${e.supports}] ${e.title} — ${e.url}`);
        lines.push(`  ${e.snippet}`);
      }
    }
    if (claim.test) {
      lines.push("");
      lines.push(`**Cheapest test** · ${claim.test.cost} · ${claim.test.time}`);
      lines.push("");
      lines.push(claim.test.method);
      lines.push("");
      lines.push(`- Proceed if: ${claim.test.confirms}`);
      lines.push(`- Stop if: ${claim.test.breaks}`);
    }
    lines.push("");
  }

  if (analysis.failureModes.length) {
    lines.push("## Pre-mortem: how this fails in a year");
    lines.push("");
    for (const mode of analysis.failureModes) {
      lines.push(`- **${mode.likelihood}** (${mode.claimRef}) ${mode.scenario}`);
      lines.push(`  - First sign: ${mode.earlyWarning}`);
    }
    lines.push("");
  }

  lines.push("## What to do this week");
  lines.push("");
  const withTests = analysis.claims.filter((c) => c.test).slice(0, 3);
  if (withTests.length === 0) {
    lines.push("_No tests were designed in this run._");
  } else {
    withTests.forEach((c, i) => {
      lines.push(`${i + 1}. **${c.claim}** — ${c.test!.method} (${c.test!.cost}, ${c.test!.time})`);
    });
  }
  lines.push("");

  if (analysis.notes.length) {
    lines.push("## Notes on this run");
    lines.push("");
    for (const note of analysis.notes) lines.push(`- ${note}`);
    lines.push("");
  }

  lines.push("---");
  lines.push("");
  lines.push(
    "_Generated by Load-Bearing. A claim marked fact or contradicted has a URL behind it; everything else is unverified. Nothing here is evidence you did not collect._"
  );

  return lines.join("\n");
}

/** A compact JSON export, for feeding the claim list into another tool. */
export function toJson(analysis: Analysis): string {
  return JSON.stringify(analysis, null, 2);
}

export function priorityClaims(analysis: Analysis, count = 6): Claim[] {
  return analysis.claims.slice(0, count);
}
