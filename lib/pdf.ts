"use client";

import type { Analysis } from "./schema";
import { bandLabel } from "./score";

/**
 * PDF export: two pages of A4, no table layouts, no chrome. jsPDF is loaded
 * only when someone clicks, so it never touches the first load.
 */
export async function downloadPdf(analysis: Analysis) {
  const { jsPDF } = await import("jspdf");
  const doc = new jsPDF({ unit: "pt", format: "a4" });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 52;
  const width = pageWidth - margin * 2;
  let y = margin;

  const ensure = (needed: number) => {
    if (y + needed > pageHeight - margin) {
      doc.addPage();
      y = margin;
    }
  };

  const wrapped = (
    text: string,
    size: number,
    style: "normal" | "bold" | "italic",
    color: [number, number, number],
    gap = 4
  ) => {
    doc.setFont("helvetica", style);
    doc.setFontSize(size);
    doc.setTextColor(...color);
    const lines = doc.splitTextToSize(text, width) as string[];
    for (const line of lines) {
      ensure(size + 4);
      doc.text(line, margin, y);
      y += size + gap;
    }
  };

  // Masthead
  wrapped("LOAD-BEARING", 9, "bold", [180, 69, 31], 2);
  wrapped(analysis.title, 20, "bold", [25, 23, 19], 6);
  wrapped(
    `${new Date(analysis.createdAt).toLocaleDateString("en-GB", {
      year: "numeric",
      month: "long",
      day: "numeric",
    })} · ${analysis.claims.length} claims, ranked by what collapses if they are wrong`,
    9,
    "normal",
    [110, 104, 96],
    10
  );

  doc.setDrawColor(226, 220, 208);
  doc.line(margin, y, pageWidth - margin, y);
  y += 16;

  wrapped(analysis.summary, 10.5, "normal", [60, 57, 52], 5);
  y += 10;

  for (const claim of analysis.claims) {
    ensure(90);
    wrapped(
      `${claim.rank}.  ${claim.claim}`,
      12,
      "bold",
      [25, 23, 19],
      5
    );
    wrapped(
      `${bandLabel(claim.priority).toUpperCase()}  ·  impact ${claim.impact}/5  ·  confidence ${claim.confidence}  ·  ${claim.category}  ·  ${claim.status}`,
      8.5,
      "bold",
      claim.priority >= 8 ? [150, 55, 25] : [110, 104, 96],
      4
    );
    if (claim.source !== "implied") {
      wrapped(`“${claim.source}”`, 9, "italic", [110, 104, 96], 4);
    }
    wrapped(claim.reasoning, 10, "normal", [60, 57, 52], 6);
    if (claim.test) {
      wrapped(`TEST · ${claim.test.cost} · ${claim.test.time}`, 8.5, "bold", [60, 57, 52], 3);
      wrapped(claim.test.method, 9.5, "normal", [60, 57, 52], 4);
      wrapped(`Proceed if: ${claim.test.confirms}`, 9, "normal", [51, 80, 63], 3);
      wrapped(`Stop if: ${claim.test.breaks}`, 9, "normal", [150, 57, 27], 6);
    }
    y += 8;
  }

  if (analysis.failureModes.length) {
    ensure(60);
    y += 6;
    wrapped("PRE-MORTEM: HOW THIS FAILS IN A YEAR", 9, "bold", [180, 69, 31], 8);
    for (const mode of analysis.failureModes) {
      wrapped(`${mode.claimRef} · ${mode.likelihood}`, 8.5, "bold", [110, 104, 96], 3);
      wrapped(mode.scenario, 9.5, "normal", [60, 57, 52], 4);
      wrapped(`First sign: ${mode.earlyWarning}`, 9, "italic", [110, 104, 96], 7);
    }
  }

  ensure(40);
  y += 4;
  doc.setDrawColor(226, 220, 208);
  doc.line(margin, y, pageWidth - margin, y);
  y += 12;
  wrapped(
    "Generated by Load-Bearing. A claim marked fact or contradicted has a URL behind it; everything else is unverified.",
    8,
    "italic",
    [138, 131, 122],
    3
  );

  const filename = `${slug(analysis.title)}.pdf`;
  doc.save(filename);
}

function slug(title: string): string {
  return (
    title
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-|-$/g, "")
      .slice(0, 48) || "load-bearing-report"
  );
}
